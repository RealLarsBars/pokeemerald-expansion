def make_sheet():
    """Draws the 128x16 sheet with Pillow (dev-time only)."""
    from PIL import Image
    base = Image.open(os.path.join(HERE, '..', BADGES))
    im = Image.new('P', (128, 16), 0)
    im.putpalette(base.getpalette()[:48])
    for n, (_, art) in enumerate(SIGILS):
        rows = art.strip('\n').split('\n')
        assert len(rows) == 16 and all(len(r) == 16 for r in rows), (n, [len(r) for r in rows])
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                im.putpixel((n * 16 + x, y), INDEX[ch])
    im.save(SHEET, bits=4)
    return SHEET


def apply(ov):
    """Puts the sigil sheet over the badge sheet. Returns report lines."""
    with open(SHEET, 'rb') as f:
        ov.write_bytes(BADGES, f.read())
    return ['TRAINER CARD badges are now house sigils: ' + ', '.join(d.split(': ')[1] for d, _ in SIGILS) + '.']


if __name__ == '__main__':
    print(make_sheet())
